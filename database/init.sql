-- =====================================================================
-- FloodGuard - criação do banco de dados (PostgreSQL)
-- Baseado na versão mais recente do código (entidades Regiao, Ocorrencia,
-- Alerta e LeituraChuva). Tipos e colunas espelham as classes Java.
--
-- Este script só roda na PRIMEIRA criação do banco.
-- Para recriar do zero:  docker compose down -v  e  docker compose up -d
-- =====================================================================

-- ---------------------------------------------------------------------
-- regioes  <-  model/Regiao.java
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS regioes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(255)     NOT NULL,
    latitude        DOUBLE PRECISION NOT NULL,
    longitude       DOUBLE PRECISION NOT NULL,
    nivel_risco     VARCHAR(255)     NOT NULL DEFAULT 'NORMAL'
                    CHECK (nivel_risco IN ('NORMAL', 'ATENCAO', 'RISCO', 'EMERGENCIA')),
    chuva_por_hora  DOUBLE PRECISION NOT NULL DEFAULT 0
);

-- ---------------------------------------------------------------------
-- ocorrencias  <-  model/Ocorrencia.java
-- regiao_id é OBRIGATÓRIO (@JoinColumn nullable = false)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ocorrencias (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regiao_id  BIGINT           NOT NULL,
    descricao  VARCHAR(255)     NOT NULL,
    latitude   DOUBLE PRECISION NOT NULL,
    longitude  DOUBLE PRECISION NOT NULL,
    data_hora  TIMESTAMP(6)     NOT NULL,
    CONSTRAINT fk_ocorrencias_regiao FOREIGN KEY (regiao_id) REFERENCES regioes (id)
);

-- ---------------------------------------------------------------------
-- alertas  <-  model/Alerta.java
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS alertas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regiao_id    BIGINT           NOT NULL,
    titulo       VARCHAR(255)     NOT NULL,
    mensagem     VARCHAR(1000)    NOT NULL,
    nivel_risco  VARCHAR(255)     NOT NULL
                 CHECK (nivel_risco IN ('NORMAL', 'ATENCAO', 'RISCO', 'EMERGENCIA')),
    data_hora    TIMESTAMP(6)     NOT NULL,
    latitude     DOUBLE PRECISION NOT NULL,
    longitude    DOUBLE PRECISION NOT NULL,
    CONSTRAINT fk_alertas_regiao FOREIGN KEY (regiao_id) REFERENCES regioes (id)
);

-- ---------------------------------------------------------------------
-- leituras_chuva  <-  model/LeituraChuva.java
-- fonte pode ficar vazia (a classe Java não a torna obrigatória)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS leituras_chuva (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regiao_id       BIGINT           NOT NULL,
    chuva_por_hora  DOUBLE PRECISION NOT NULL,
    fonte           VARCHAR(50),
    data_hora       TIMESTAMP(6)     NOT NULL,
    CONSTRAINT fk_leituras_regiao FOREIGN KEY (regiao_id) REFERENCES regioes (id)
);

-- ---------------------------------------------------------------------
-- Índices (consultas por região e por data)
-- ---------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_ocorrencias_regiao_data ON ocorrencias    (regiao_id, data_hora DESC);
CREATE INDEX IF NOT EXISTS idx_alertas_regiao_data     ON alertas        (regiao_id, data_hora DESC);
CREATE INDEX IF NOT EXISTS idx_leituras_regiao_data    ON leituras_chuva (regiao_id, data_hora DESC);
